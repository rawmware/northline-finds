# (title, meta description) for each hand-editable page in content/
CONTENT_PAGES = [
    ("about.html", "About Us", "How Northline Finds chooses products, and what we stand for."),
    ("faq.html", "FAQ", "Answers about shipping, returns, payments, and how Northline Finds works."),
    ("shipping.html", "Shipping Info", "How long shipping takes, tracking, and shipping costs at Northline Finds."),
    ("refunds.html", "Returns & Refunds", "Our 30-day return policy: full refunds, no questions asked."),
    ("contact.html", "Contact Us", "Get in touch with Northline Finds — real human support."),
]


def build_content_pages():
    content_dir = STORE / "content"
    built = []
    for slug, title, desc in CONTENT_PAGES:
        frag = content_dir / (slug[:-5] + ".html")
        if not frag.exists():
            print(f"  (skip {slug}: content/{frag.name} not found)")
            continue
        (STORE / slug).write_text(page(title, desc, frag.read_text(encoding="utf-8")), encoding="utf-8")
        built.append(slug)
    return built


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--products", default=str(RESEARCH_JSON))
    args = ap.parse_args()

    products = load_products(args.products)
    if not products:
        raise SystemExit("No products found in " + args.products)
    links = load_stripe_links()

    write_products_js(products, links)
    write_catalog_js(products)

    (STORE / "index.html").write_text(build_index(products, links), encoding="utf-8")
    prod_dir = STORE / "products"
    prod_dir.mkdir(exist_ok=True)
    wanted = set()
    for p in products:
        fname = p["_safe"] + ".html"
        wanted.add(fname)
        (prod_dir / fname).write_text(build_product_page(p, products, links), encoding="utf-8")
    for stale in prod_dir.glob("*.html"):
        if stale.name not in wanted:
            stale.unlink()
            print(f"  removed stale page: products/{stale.name}")
    (STORE / "cart.html").write_text(build_cart(), encoding="utf-8")
    content_built = build_content_pages()

    missing_img = [p.get("id") for p in products if image_for(p) == PLACEHOLDER]
    missing_links = [p.get("id") for p in products if not links.get(p.get("id"), "")]
    print(f"Built {len(products)} products -> index.html, cart.html, {len(products)} product pages, {len(content_built)} content pages.")
    print(f"Images: {len(products) - len(missing_img)}/{len(products)} have photos; placeholder used for: {missing_img or 'none'}")
    print(f"Stripe links: {len(products) - len(missing_links)}/{len(products)} set; missing for: {missing_links or 'none'}")


if __name__ == "__main__":
    main()
