def esc(s):
    return html.escape("" if s is None else str(s), quote=True)


def money(n):
    try:
        return f"${float(n):.2f}"
    except (TypeError, ValueError):
        return "$0.00"


def safe_id(pid):
    s = re.sub(r"[^a-z0-9\-_]", "-", str(pid).lower()).strip("-")
    return s or "product"


def load_products(path):
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if isinstance(data, dict) and "products" in data:
        data = data["products"]
    products = []
    for p in data:
        p = dict(p)
        p["_safe"] = safe_id(p.get("id", "product"))
        products.append(p)
    return products


def image_for(p):
    for ext in IMG_EXTS:
        f = STORE / "assets" / "img" / (p["_safe"] + ext)
        if f.exists():
            return f"assets/img/{p['_safe']}{ext}"
    return PLACEHOLDER


# ---------- existing stripe links ----------
def load_stripe_links():
    cfg = STORE / "assets" / "js" / "products.js"
    links = {}
    if not cfg.exists():
        return links
    text = cfg.read_text(encoding="utf-8")
    m = re.search(r"stripeLinks\s*:\s*\{", text)
    if not m:
        return links
    depth, start = 0, m.end() - 1
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                block = text[start:i + 1]
                break
    else:
        return links
    for km in re.finditer(r'"([^"]+)"\s*:\s*"([^"]*)"', block):
        links[km.group(1)] = km.group(2)
    return links


def write_products_js(products, links):
    lines = [
        "/* %s store config." % STORE_NAME,
        " * Paste each product's Stripe Payment Link below, then re-run:  python3 build.py",
        " * (build.py preserves links you've already filled in.)",
        " */",
        "window.STORE_CONFIG = {",
        '  storeName: "%s",' % STORE_NAME,
        '  contactEmail: "%s",' % CONTACT_EMAIL,
        "  stripeLinks: {",
    ]
    for p in products:
        pid = p.get("id", "")
        link = links.get(pid, "")
        lines.append('    "%s": "%s",' % (pid.replace('"', ""), link.replace('"', "")))
    lines += ["  }", "};", ""]
    (STORE / "assets" / "js" / "products.js").write_text("\n".join(lines), encoding="utf-8")


def write_catalog_js(products):
    cat = {}
    for p in products:
        pid = p.get("id", "")
        cat[pid] = {
            "id": pid,
            "name": p.get("name", ""),
            "tagline": p.get("tagline", ""),
            "retail_price": float(p.get("retail_price") or 0),
            "category": p.get("category", ""),
            "image": image_for(p),
        }
    out = "/* generated by build.py — do not edit by hand */\nwindow.CATALOG = " + json.dumps(cat, indent=2) + ";\n"
    (STORE / "assets" / "js" / "catalog.js").write_text(out, encoding="utf-8")


